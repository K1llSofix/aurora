const DICTS = { ru, en };
let lang = 'ru';

export function setLanguage(code) {
  lang = DICTS[code] ? code : 'en';
  document.documentElement.lang = lang;
}

export function language() {
  return lang;
}

/** Resolves "auto" against the system locale. */
export function resolveLanguage(setting, locale) {
  if (setting && setting !== 'auto') return setting;
  return /^(ru|uk|be|kk)/i.test(locale || navigator.language) ? 'ru' : 'en';
}

function fill(text, params) {
  return text.replace(/\{(\w+)\}/g, (all, key) => (params && params[key] !== undefined ? params[key] : all));
}

export function t(key, params) {
  const text = DICTS[lang][key] ?? en[key] ?? key;
  return fill(text.split('|')[0], params);
}

/** A plural string: Russian picks one of three forms, English one of two. */
export function tp(key, n, params = {}) {
  const forms = (DICTS[lang][key] ?? en[key] ?? key).split('|');
  let i;
  if (lang === 'ru') {
    const m10 = n % 10;
    const m100 = n % 100;
    i = m10 === 1 && m100 !== 11 ? 0 : m10 >= 2 && m10 <= 4 && (m100 < 10 || m100 >= 20) ? 1 : 2;
  } else {
    i = n === 1 ? 0 : 1;
  }
  return fill(forms[Math.min(i, forms.length - 1)], { n: formatNumber(n), ...params });
}

export function formatNumber(n) {
  return new Intl.NumberFormat(lang === 'ru' ? 'ru-RU' : 'en-US').format(n);
}

/** 12 400 000 → "12,4 млн" / "12.4M" for download counters. */
export function compactNumber(n) {
  return new Intl.NumberFormat(lang === 'ru' ? 'ru-RU' : 'en-US', { notation: 'compact', maximumFractionDigits: 1 }).format(n);
}

export function formatBytes(bytes) {
  if (bytes >= 1024 ** 3) return `${(bytes / 1024 ** 3).toFixed(1).replace('.', lang === 'ru' ? ',' : '.')} ${t('common.gb')}`;
  if (bytes >= 1024 ** 2) return `${(bytes / 1024 ** 2).toFixed(bytes >= 100 * 1024 ** 2 ? 0 : 1).replace('.', lang === 'ru' ? ',' : '.')} ${t('common.mb')}`;
  return `${Math.max(1, Math.round(bytes / 1024))} ${t('common.kb')}`;
}

/** Memory in megabytes as "4 ГБ" or "3,5 ГБ". */
export function formatMemory(mb) {
  const gb = mb / 1024;
  const text = Number.isInteger(gb) ? String(gb) : gb.toFixed(1).replace('.', lang === 'ru' ? ',' : '.');
  return `${text} ${t('common.gb')}`;
}

export function timeAgo(ms) {
  const diff = Date.now() - ms;
  const min = Math.floor(diff / 60000);
  if (min < 1) return t('time.now');
  if (min < 60) return tp('time.minutes', min);
  const hours = Math.floor(min / 60);
  if (hours < 24) return tp('time.hours', hours);
  const days = Math.floor(hours / 24);
  if (days === 1) return t('time.yesterday');
  if (days < 30) return tp('time.days', days);
  return new Date(ms).toLocaleDateString(lang === 'ru' ? 'ru-RU' : 'en-US', { day: 'numeric', month: 'long' });
}

export function formatDate(iso) {
  const d = new Date(iso);
  if (Number.isNaN(d.getTime())) return '';
  return d.toLocaleDateString(lang === 'ru' ? 'ru-RU' : 'en-US', { day: 'numeric', month: 'long', year: 'numeric' });
}

/** Text for an error object from the main process ({code, detail, params}). */
export function errorText(err) {
  if (!err) return t('error.unknown');
  const key = `error.${err.code}`;
  const known = DICTS[lang][key] ?? en[key];
  return known ? t(key, err.params) : t('error.unknown');
}
